export const calculateOrderSummary = (
  items: Array<{ price: number; quantity?: number; name?: string }>,
  selectedPaymentMethod: PaymentMethodSetting | null | undefined,
  shippingFee: number = 7.00,
  freeShippingThreshold: number = 50.00
) => {
  const subtotal = (items || []).reduce((acc, it) => acc + ((it.price || 0) * (it.quantity || 1)), 0);
  const isMethodActive = selectedPaymentMethod ? selectedPaymentMethod.enabled !== false : false;
  const discountPercentage = isMethodActive ? (Number(selectedPaymentMethod?.discountPercentage) || 0) : 0;
  const discount = discountPercentage > 0 ? (subtotal * (discountPercentage / 100)) : 0;
  const subtotalWithDiscount = subtotal - discount;
  const effectiveShipping = (freeShippingThreshold > 0 && subtotal >= freeShippingThreshold) ? 0 : shippingFee;
  const total = subtotalWithDiscount + effectiveShipping;

  return {
    subtotal,
    discountPercentage,
    discount,
    subtotalWithDiscount,
    shippingFee: effectiveShipping,
    total,
  };
};

